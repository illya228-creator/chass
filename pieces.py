
# Создаём шахматную доску с начальной расстановкой
def create_board():
    return [
        # Чёрные фигуры
        ["br", "bn", "bb", "bq", "bk", "bb", "bn", "br"],

        # Чёрные пешки
        ["bp", "bp", "bp", "bp", "bp", "bp", "bp", "bp"],

        # Пустые клетки
        ["", "", "", "", "", "", "", ""],
        ["", "", "", "", "", "", "", ""],
        ["", "", "", "", "", "", "", ""],
        ["", "", "", "", "", "", "", ""],

        # Белые пешки
        ["wp", "wp", "wp", "wp", "wp", "wp", "wp", "wp"],

        # Белые фигуры
        ["wr", "wn", "wb", "wq", "wk", "wb", "wn", "wr"],
    ]


# Перемещаем фигуру на новую клетку
def move_piece(board, start_pos, end_pos):
    sx, sy = start_pos
    ex, ey = end_pos

    # Получаем перемещаемую фигуру
    piece = board[sy][sx]

    # Не перемещаем пустую клетку
    if not piece:
        return

    # Превращаем пешку в ферзя на последней горизонтали
    if piece[1] == "p" and ey in (0, 7):
        board[ey][ex] = piece[0] + "q"
    else:
        # Переносим фигуру на целевую клетку
        board[ey][ex] = piece

    # Освобождаем начальную клетку
    board[sy][sx] = ""
